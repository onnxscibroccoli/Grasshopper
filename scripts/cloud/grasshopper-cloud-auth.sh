#!/usr/bin/env bash
# Grasshopper OCI + Google Cloud OAuth bootstrap.
# Usage: grasshopper-cloud-auth.sh status | google | oci | all
# Profile: existing OMNIKALI, region: us-ashburn-1.
# Manual OAuth via trusted browser + phone Termux gcloud remote-bootstrap.
# Never print tokens, credentials, auth files or OAuth URLs into logs.
set -Eeuo pipefail
umask 077
export CLOUDSDK_CORE_DISABLE_PROMPTS=0
HOME=${HOME:-/home/grasshopper}
ROOT="$HOME/.local/state/grasshopper-cloud-auth"
mkdir -p "$ROOT"
chmod 700 "$ROOT"
PROFILE=OMNIKALI
REGION=us-ashburn-1
PROJECT=omnikali
CONFIG="$HOME/.oci/config"
STATUS_FILE="$ROOT/last-status.txt"
MODE="${1:-status}"
if [[ ! "$MODE" =~ ^(status|google|oci|all)$ ]]; then
    echo "Usage: $0 [status|google|oci|all]" >&2
    exit 2
fi
stamp() { date '+%Y-%m-%dT%H:%M:%S%z'; }
say() { printf '\n[%s] %s\n' "$(stamp)" "$*"; }
persist() { printf '%s | %s\n' "$(stamp)" "$1" >>"$STATUS_FILE"; }
success() { say "PASS: $1"; persist "PASS $1"; }
warning() { say "WARN: $1"; persist "WARN $1"; }
preflight() {
    say "STEP 1/5: Existing toolchain and storage"
    command -v oci >/dev/null || { warning "OCI CLI missing"; return 3; }
    command -v gcloud >/dev/null || { warning "Google Cloud CLI missing"; return 3; }
    printf 'OCI: '; oci --version
    printf 'Google: '; gcloud version | head -1
    df -h / | tail -1
    if [[ ! -f "$CONFIG" ]]; then warning "OCI config missing"; return 3; fi
    if ! grep -q '^\[OMNIKALI\]' "$CONFIG"; then
        warning "Existing OMNIKALI OCI profile not found"; return 3
    fi
    success "Existing toolchain/profile present; no packages installed"
}
google_cli_ok() {
    timeout 35 gcloud projects describe "$PROJECT" --format='value(projectId)' --quiet >/dev/null 2>&1
}
google_adc_ok() {
    timeout 20 gcloud auth application-default print-access-token --quiet >/dev/null 2>&1
}
oci_ok() {
    timeout 12 oci session validate --local --auth security_token --profile "$PROFILE" --config-file "$CONFIG" >/dev/null 2>&1 &&
    timeout 30 oci iam availability-domain list --auth security_token --profile "$PROFILE" --config-file "$CONFIG" --region "$REGION" --no-retry --output json >/dev/null 2>&1
}
show_status() {
    say "CURRENT VERIFIED ACCESS (read-only; secrets hidden)"
    google_cli_ok && echo "GCLOUD_API=PASS" || echo "GCLOUD_API=FAIL"
    google_adc_ok && echo "GOOGLE_ADC=PASS" || echo "GOOGLE_ADC=MISSING_OR_INVALID"
    oci_ok && echo "OCI_OMNIKALI=PASS" || echo "OCI_OMNIKALI=EXPIRED_OR_INVALID"
    echo "DEFAULT_GCLOUD_PROJECT=$(gcloud config get-value core/project 2>/dev/null || true)"
    echo "DEV_QUOTA_PROJECT=$PROJECT (only applied when ADC OAuth is completed)"
    echo "NO_CLOUD_RESOURCE_MODIFICATIONS"
}
google_login() {
    say "STEP 2/5: Google Cloud CLI"
    if google_cli_ok; then success "Existing Google CLI OAuth authenticates to $PROJECT"; else
        say "Google CLI login required. Use phone Termux (has gcloud) for remote-bootstrap."
        echo "Complete the instructions generated by Google; DO NOT post bootstrap URLs in chat."
        gcloud auth login --no-browser
        google_cli_ok || { warning "Google CLI API validation failed"; return 2; }
        success "Google CLI OAuth + project API"
    fi
    say "STEP 3/5: Google Application Default Credentials"
    if google_adc_ok; then
        success "Existing ADC token refresh"
    else
        if [[ -e "$HOME/.config/gcloud/application_default_credentials.json" ]]; then
            local adc_backup="$ROOT/adc-backup-$(date +%Y%m%d-%H%M%S)"
            mkdir -p "$adc_backup"
            cp -p "$HOME/.config/gcloud/application_default_credentials.json" "$adc_backup/"
        fi
        echo "ADC OAuth needed for Python SDKs. Follow the gcloud remote-bootstrap"
        echo "instructions on phone Termux + Chrome, then paste its result into this terminal."
        echo "The ADC quota project will be $PROJECT (may incur charges for used APIs)."
        gcloud auth application-default login --no-browser --project="$PROJECT"
        google_adc_ok || { warning "ADC token refresh did not pass"; return 2; }
        success "Google development ADC OAuth+refresh (no tokens shown)"
    fi
}
oci_login() {
    say "STEP 4/5: OCI OMNIKALI signed session"
    if oci_ok; then
        success "Existing OCI security-token API"; return 0
    fi
    local backup="$ROOT/oci-config-pre-$(date +%Y%m%d-%H%M%S)"
    mkdir -p "$backup"
    cp -a "$HOME/.oci" "$backup/oci"
    success "Private backup of existing OCI profile created"
    say "Oracle browser OAuth required. Use a trusted local phone browser."
    echo "Follow the OCI CLI no-browser sign-in instructions shown below."
    echo "Profile preserved: $PROFILE ; region: $REGION."
    oci session authenticate --no-browser --region "$REGION" --profile-name "$PROFILE" --config-location "$CONFIG"
    oci_ok || { warning "OCI session signed IAM request failed"; return 2; }
    success "OCI OMNIKALI browser OAuth + signed API"
}
finish() {
    say "STEP 5/5: Validation"
    show_status
    say "DONE. This script did not install packages or change cloud resources."
    echo "Private non-token status journal: $STATUS_FILE"
}
if [[ "$MODE" == status ]]; then
    show_status
else
    preflight
    if [[ "$MODE" == google || "$MODE" == all ]]; then google_login; fi
    if [[ "$MODE" == oci || "$MODE" == all ]]; then oci_login; fi
    finish
fi
